// Theme bootstrap — runs before React mounts so the saved theme is applied
// without a flash of unstyled colors. Mirrors the palette logic in
// src/theme.ts (kept intentionally simple / self-contained so we don't need
// a bundler here).

(function () {
  var STORAGE_KEY = 'ezsale:theme';
  var DEFAULTS = { primary: '#84eb0a', secondary: '#13171c' };

  function safeRead() {
    try {
      var raw = localStorage.getItem(STORAGE_KEY);
      if (!raw) return DEFAULTS;
      var parsed = JSON.parse(raw);
      if (typeof parsed.primary !== 'string' || typeof parsed.secondary !== 'string') {
        return DEFAULTS;
      }
      return { primary: parsed.primary, secondary: parsed.secondary };
    } catch (_e) {
      return DEFAULTS;
    }
  }

  function hexToRgb(hex) {
    var cleaned = String(hex).replace('#', '').trim();
    var full = cleaned.length === 3
      ? cleaned.split('').map(function (c) { return c + c; }).join('')
      : cleaned;
    var num = parseInt(full, 16);
    if (isNaN(num)) return { r: 0, g: 0, b: 0 };
    return { r: (num >> 16) & 0xff, g: (num >> 8) & 0xff, b: num & 0xff };
  }

  function clamp(v) { return Math.max(0, Math.min(255, v)); }
  function toHex(v) { return clamp(v).toString(16).padStart(2, '0'); }
  function rgbToHex(r, g, b) { return '#' + toHex(r) + toHex(g) + toHex(b); }

  // ---- HSL math (matches src/theme.ts) ----
  // The picked color always becomes stop 500; the other stops are
  // tints (50-400) and shades (600-900) of the same hue, generated by
  // walking the HSL lightness axis instead of mixing toward white/black.

  function rgbToHsl(r, g, b) {
    var rn = r / 255, gn = g / 255, bn = b / 255;
    var max = Math.max(rn, gn, bn);
    var min = Math.min(rn, gn, bn);
    var l = (max + min) / 2;
    var h = 0, s = 0;
    if (max !== min) {
      var d = max - min;
      s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
      if (max === rn) h = (gn - bn) / d + (gn < bn ? 6 : 0);
      else if (max === gn) h = (bn - rn) / d + 2;
      else h = (rn - gn) / d + 4;
      h *= 60;
    }
    return { h: h, s: s, l: l };
  }

  function hslToHex(h, s, l) {
    var c = (1 - Math.abs(2 * l - 1)) * s;
    var x = c * (1 - Math.abs(((h / 60) % 2) - 1));
    var m = l - c / 2;
    var r = 0, g = 0, b = 0;
    if (h < 60) { r = c; g = x; }
    else if (h < 120) { r = x; g = c; }
    else if (h < 180) { g = c; b = x; }
    else if (h < 240) { g = x; b = c; }
    else if (h < 300) { r = x; b = c; }
    else { r = c; b = x; }
    return rgbToHex(
      Math.round((r + m) * 255),
      Math.round((g + m) * 255),
      Math.round((b + m) * 255)
    );
  }

  var LIGHTNESS_BY_STOP = {
    50: 0.97, 100: 0.94, 200: 0.86, 300: 0.77, 400: 0.66,
    500: NaN, 600: 0.42, 700: 0.34, 800: 0.26, 900: 0.18,
  };

  function buildScale(hex) {
    var rgb = hexToRgb(hex);
    var hsl = rgbToHsl(rgb.r, rgb.g, rgb.b);
    var stops = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900];
    return stops.map(function (stop) {
      var target = stop === 500 ? hsl.l : LIGHTNESS_BY_STOP[stop];
      var scale = stop <= 100 || stop >= 800 ? 0.6 : (stop === 500 ? 1 : 0.9);
      var sAdj = Math.max(0, Math.min(1, hsl.s * scale));
      return hslToHex(hsl.h, sAdj, target);
    });
  }

  function applyTheme(theme) {
    var root = document.documentElement;
    var brand = buildScale(theme.primary);
    var ink = buildScale(theme.secondary);
    // The stop list mirrors the Tailwind scale (50, 100, 200, ..., 900).
    // Each class like `bg-brand-500` reads `var(--brand-500-rgb)`; if the
    // variable is unset the rule resolves to `rgb(undefined / 1)` which is
    // invalid, so we always write all 10 stops.
    var stops = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900];
    for (var i = 0; i < stops.length; i++) {
      var brandRgb = hexToRgb(brand[i]);
      var inkRgb = hexToRgb(ink[i]);
      root.style.setProperty(
        '--brand-' + stops[i] + '-rgb',
        brandRgb.r + ' ' + brandRgb.g + ' ' + brandRgb.b
      );
      root.style.setProperty(
        '--ink-' + stops[i] + '-rgb',
        inkRgb.r + ' ' + inkRgb.g + ' ' + inkRgb.b
      );
    }
    // Compute the readable text color for the 500 stop of each scale using
    // sRGB luminance (gamma-corrected). Used by .btn-primary, .pos-pill-active
    // and .pos-add-btn so the text color always matches the live preview.
    var brand500 = hexToRgb(brand[5]);
    var ink500 = hexToRgb(ink[5]);
    var brandText = isDark(brand500) ? '255 255 255' : '19 23 28';
    var inkText = isDark(ink500) ? '255 255 255' : '19 23 28';
    root.style.setProperty('--text-on-brand-rgb', brandText);
    root.style.setProperty('--text-on-ink-rgb', inkText);
    root.style.setProperty('--theme-primary', theme.primary);
    root.style.setProperty('--theme-secondary', theme.secondary);
  }

  function srgbLum(c) {
    var v = c / 255;
    return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4);
  }

  function isDark(rgb) {
    var l = 0.2126 * srgbLum(rgb.r) + 0.7152 * srgbLum(rgb.g) + 0.0722 * srgbLum(rgb.b);
    return l < 0.55;
  }

  applyTheme(safeRead());
})();
